CREATE TABLE IF NOT EXISTS rol (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT UNIQUE NOT NULL,
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    rol_id INTEGER NOT NULL REFERENCES rol(id) ON DELETE RESTRICT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS favoritos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciudad TEXT NOT NULL,
    region TEXT NOT NULL,
    latitud DOUBLE PRECISION NOT NULL,
    longitud DOUBLE PRECISION NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS historial_consultas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciudad TEXT NOT NULL,
    region TEXT,
    temperatura DOUBLE PRECISION,
    sensacion_termica DOUBLE PRECISION,
    condicion TEXT,
    humedad INTEGER,
    viento_kmh DOUBLE PRECISION,
    indice_uv DOUBLE PRECISION,
    consultado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

